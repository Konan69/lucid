import { assert, effect, log } from "./load.mjs";
const { Cause, Deferred, Effect, Fiber, Latch, PubSub, Queue, Semaphore, Stream, SubscriptionRef } = effect;
const immediate = (program) => Effect.forkChild(program, { startImmediately: true });

await Effect.runPromise(Effect.scoped(Effect.gen(function* () {
  for (const kind of ["Deferred", "Latch"]) {
    const gate = yield* (kind === "Deferred" ? Deferred.make() : Latch.make());
    const wait = kind === "Deferred" ? Deferred.await(gate) : Latch.await(gate);
    const observed = [];
    const fibers = [];
    for (const id of [1, 2, 3]) fibers.push(yield* immediate(Effect.andThen(wait, Effect.sync(() => observed.push(id)))));
    yield* Fiber.interrupt(fibers[1]);
    yield* (kind === "Deferred" ? Deferred.succeed(gate, "ready") : Latch.release(gate));
    yield* Fiber.join(fibers[0]);
    yield* Fiber.join(fibers[2]);
    assert.deepEqual(observed, [1, 3]);
    log(`${kind}.wakeOrder`, observed);
    if (kind === "Latch") {
      const late = yield* immediate(Latch.await(gate));
      const closedAfterRelease = !Latch.isOpen(gate);
      yield* Latch.open(gate);
      yield* Fiber.join(late);
      assert(closedAfterRelease);
      log("Latch.releaseKeepsClosed", closedAfterRelease);
    }
  }
  const sem = yield* Semaphore.make(2);
  yield* Semaphore.take(sem, 2);
  const observed = [];
  const large = yield* immediate(Effect.andThen(Semaphore.take(sem, 2), Effect.sync(() => observed.push("large"))));
  const small = yield* immediate(Effect.andThen(Semaphore.take(sem, 1), Effect.sync(() => observed.push("small"))));
  yield* Semaphore.release(sem, 1);
  yield* Fiber.join(small);
  yield* Semaphore.release(sem, 2);
  yield* Fiber.join(large);
  assert.deepEqual(observed, ["small", "large"]);
  log("Semaphore.mixedPermitOrder", observed);
  const one = yield* Semaphore.make(1);
  yield* Semaphore.take(one, 1);
  const fifo = [];
  const waiters = [];
  for (const id of [1, 2, 3]) waiters.push(yield* immediate(Effect.andThen(Semaphore.take(one, 1), Effect.sync(() => fifo.push(id)))));
  for (const waiter of waiters) { yield* Semaphore.release(one, 1); yield* Fiber.join(waiter); }
  assert.deepEqual(fifo, [1, 2, 3]);
  log("Semaphore.equalPermitOrder", fifo);
  const q = yield* Queue.bounded(1);
  yield* Queue.offer(q, "buffered");
  const blocked = yield* immediate(Queue.offer(q, "waiting"));
  yield* Queue.shutdown(q);
  const offer = yield* Fiber.join(blocked);
  const take = yield* Effect.exit(Queue.take(q));
  const size = yield* Queue.size(q);
  assert.equal(offer, false);
  assert(Cause.hasInterrupts(take.cause));
  assert.equal(size, 0);
  log("Queue.shutdown", { blockedOffer: offer, takeInterrupted: Cause.hasInterrupts(take.cause), size });
  const empty = yield* Queue.unbounded();
  const taker = yield* immediate(Effect.exit(Queue.take(empty)));
  yield* Queue.shutdown(empty);
  const taking = yield* Fiber.join(taker);
  assert(Cause.hasInterrupts(taking.cause));
  log("Queue.pendingTakeInterrupted", true);
  const draining = yield* Queue.unbounded();
  yield* Queue.offer(draining, "retained");
  yield* Queue.end(draining);
  const drained = yield* Queue.take(draining);
  const done = yield* Effect.exit(Queue.take(draining));
  assert.equal(drained, "retained");
  log("Queue.end", { drained, terminal: done._tag, cause: done.cause.reasons.map((r) => r._tag) });
  const replay = yield* PubSub.unbounded({ replay: 2 });
  yield* PubSub.publishAll(replay, [1, 2, 3]);
  const late = yield* PubSub.subscribe(replay);
  const replayed = [yield* PubSub.take(late), yield* PubSub.take(late)];
  assert.deepEqual(replayed, [2, 3]);
  log("PubSub.lateReplay", replayed);
  const noReplay = yield* PubSub.unbounded();
  yield* PubSub.publish(noReplay, "past");
  const newSub = yield* PubSub.subscribe(noReplay);
  assert.equal(yield* PubSub.remaining(newSub), 0);
  log("PubSub.defaultReplay", 0);
  const bounded = yield* PubSub.bounded(1);
  const a = yield* PubSub.subscribe(bounded);
  const b = yield* PubSub.subscribe(bounded);
  yield* PubSub.publish(bounded, "first");
  const published = yield* Deferred.make();
  const producer = yield* immediate(Effect.andThen(PubSub.publish(bounded, "second"), Deferred.succeed(published, true)));
  yield* PubSub.take(a);
  const blockedUntilAll = !(yield* Deferred.isDone(published));
  yield* PubSub.take(b);
  yield* Fiber.join(producer);
  assert(blockedUntilAll);
  log("PubSub.backpressureWaitsForAll", blockedUntilAll);
  yield* PubSub.shutdown(bounded);
  yield* PubSub.shutdown(replay);
  yield* PubSub.shutdown(noReplay);
  const ref = yield* SubscriptionRef.make(0);
  const ready = yield* Deferred.make();
  const changes = yield* immediate(SubscriptionRef.changes(ref).pipe(Stream.tap(() => Deferred.succeed(ready, true)), Stream.take(4), Stream.runCollect));
  yield* Deferred.await(ready);
  yield* SubscriptionRef.set(ref, 1);
  yield* SubscriptionRef.set(ref, 1);
  yield* SubscriptionRef.set(ref, 2);
  const values = yield* Fiber.join(changes);
  assert.deepEqual(values, [0, 1, 1, 2]);
  log("SubscriptionRef.changes", values);
})));
