/**
 * The fingerprint of the wire: the JSON Schema of each registered schema's encoded side, in key
 * order, hashed once when this module loads. The server and a cell compare theirs
 * (`CONTRACT_HEADER` on every admission, `GET /contract`, `contract` on every refusal) to tell a
 * Worker built from other schemas, which is what made every send fail from 8 November 2026: the
 * published Worker predated the server's admission body and refused it, and nothing said why.
 *
 * Key order, not insertion order, so moving an entry does not change it; any change to a
 * registered schema's encoded shape or its annotations does.
 *
 * Effect's `Hash.string` (32 bits) is enough here: it tells two builds apart, it does not guard
 * anything, and it runs the same in the server, the Worker and a test without a crypto module.
 */
export const contractFingerprint: ContractFingerprint = ContractFingerprint.make(
  (
    Hash.string(
      JSON.stringify(
        Object.entries(wireSchemas)
          .sort(([one], [other]) => (one < other ? -1 : 1))
          .map(([name, schema]) => [name, Schema.toJsonSchemaDocument(schema)]),
      ),
    ) >>> 0
  )
    .toString(16)
    .padStart(8, '0'),
)
